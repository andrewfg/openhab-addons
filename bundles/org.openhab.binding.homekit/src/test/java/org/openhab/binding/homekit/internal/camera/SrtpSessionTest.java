package org.openhab.binding.homekit.internal.camera;

import static org.junit.jupiter.api.Assertions.*;

import java.util.Arrays;
import java.util.HexFormat;
import java.util.List;

import org.junit.jupiter.api.Test;
import org.openhab.binding.homekit.internal.camera.session.SrtpCryptoSuite;
import org.openhab.binding.homekit.internal.camera.session.SrtpParameters;
import org.openhab.binding.homekit.internal.camera.session.SrtpSession;

/**
 * Tests for {@link SrtpSession}.
 *
 * @author Andrew Fiddian-Green - Initial contribution
 */
class SrtpSessionTest {

    private static final byte[] MASTER_KEY = hex("E1F97A0D3E018BE0D64FA32C06DE4139");
    private static final byte[] MASTER_SALT = hex("0EC675AD498AFEEBB6960B3AABE6");

    private static final SrtpParameters PARAMETERS = new SrtpParameters(SrtpCryptoSuite.AES_CM_128_HMAC_SHA1_80,
            MASTER_KEY, MASTER_SALT);

    @Test
    void deriveKeysMatchRfc3711TestVectors() {
        assertArrayEquals(hex("C61E7A93744F39EE10734AFE3FF7A087"),
                SrtpSession.deriveKey(MASTER_KEY, MASTER_SALT, (byte) 0x00, 16));
        assertArrayEquals(hex("30CBBC08863D8C85D49DB34A9AE1"),
                SrtpSession.deriveKey(MASTER_KEY, MASTER_SALT, (byte) 0x02, 14));
        assertArrayEquals(hex("CEBE321F6FF7716B6FD4AB49AF256A156D38BAA4"),
                SrtpSession.deriveKey(MASTER_KEY, MASTER_SALT, (byte) 0x01, 20));
    }

    /**
     * SRTP packets generated by libsrtp 2.5.0 for the same master key and salt, SSRC and RTP packets as
     * {@link #rtpPacket(int, int, int)}, including a sequence number wrap.
     */
    private static final List<LibsrtpVector> LIBSRTP_VECTORS = List.of(new LibsrtpVector(65534, 0,
            "8060FFFE0000000012345678A3E7EC1B6EA33FC3347530126F19996DFEA9DC7821C39FD080167D7075CDF0F15745F633A5B961FF180BEE5247AFA7804A1AF477F1B9525DBF340A67ABC59A1D6FAD7E72E84C5002A51A43CA4B527AC5F7829517C53E5A7A7248"),
            new LibsrtpVector(65535, 1,
                    "8060FFFF0000000112345678727D08896A6C4E55CD8D1D67DC2F975ED937CC1CC5B9F2FDF7055A4485132973A78F319220974738EA9CC478791B07AEDF19D3A2A941ABEC4DB424B81A03DD8357DD232D00210F53D51403C38E3A489380F88E8A5E5F4A98C192"),
            new LibsrtpVector(0, 2,
                    "806000000000000212345678E8F01E897DD3C56DBDC0FB70CB736EE8365E68394B4B866149CED8FA7B787A411D0AE63790183D5282FB76573C643296AF2678196E220EFD991EECC9AC62627FBFBF35439761E27BADD6390DF6E9D8689CDCB2C6F4CD3EA89153"));

    @Test
    void protectMatchesLibsrtpVectors() {
        SrtpSession sender = SrtpSession.create(PARAMETERS);
        for (LibsrtpVector vector : LIBSRTP_VECTORS) {
            byte[] srtp = encrypt(sender, rtpPacket(vector.seq(), 0x12345678, vector.index()));
            assertArrayEquals(hex(vector.srtp()), srtp, "seq " + vector.seq());
        }
    }

    @Test
    void unprotectLibsrtpVectors() {
        SrtpSession receiver = SrtpSession.create(PARAMETERS);
        for (LibsrtpVector vector : LIBSRTP_VECTORS) {
            byte[] rtp = decrypt(receiver, hex(vector.srtp()));
            assertNotNull(rtp, "seq " + vector.seq() + " failed authentication");
            assertArrayEquals(rtpPacket(vector.seq(), 0x12345678, vector.index()), rtp, "seq " + vector.seq());
        }
    }

    @Test
    void roundTripAcrossSequenceNumberWrap() {
        SrtpSession sender = SrtpSession.create(PARAMETERS);
        SrtpSession receiver = SrtpSession.create(PARAMETERS);
        for (int i = 0; i < 70_000; i++) {
            int seq = (65_000 + i) & 0xFFFF;
            byte[] rtp = rtpPacket(seq, 0x12345678, i);
            byte[] srtp = encrypt(sender, rtp);
            assertEquals(rtp.length + 10, srtp.length);
            byte[] decrypted = decrypt(receiver, srtp);
            assertNotNull(decrypted, "packet " + i + " failed authentication");
            assertArrayEquals(rtp, decrypted);
        }
    }

    @Test
    void protectedPacketDiffersFromPlainText() {
        byte[] rtp = rtpPacket(1, 0xCAFEBABE, 0);
        byte[] srtp = encrypt(SrtpSession.create(PARAMETERS), rtp);
        assertFalse(Arrays.equals(Arrays.copyOfRange(rtp, 12, rtp.length), Arrays.copyOfRange(srtp, 12, rtp.length)));
    }

    @Test
    void tamperedPacketIsRejected() {
        byte[] srtp = encrypt(SrtpSession.create(PARAMETERS), rtpPacket(7, 0x01020304, 0));
        srtp[srtp.length - 15] ^= 0x01;
        assertNull(decrypt(SrtpSession.create(PARAMETERS), srtp));
    }

    @Test
    void packetWithWrongKeyIsRejected() {
        byte[] srtp = encrypt(SrtpSession.create(PARAMETERS), rtpPacket(7, 0x01020304, 0));
        SrtpParameters other = new SrtpParameters(SrtpCryptoSuite.AES_CM_128_HMAC_SHA1_80,
                hex("00112233445566778899AABBCCDDEEFF"), MASTER_SALT);
        assertNull(decrypt(SrtpSession.create(other), srtp));
    }

    @Test
    void truncatedPacketIsRejected() {
        assertNull(decrypt(SrtpSession.create(PARAMETERS), new byte[20]));
    }

    @Test
    void rtcpEncryptsPayloadAfterFixedHeader() {
        byte[] rtcp = rtcpReceiverReport(0x01020304, 0xCAFEBABE);
        byte[] srtcp = encryptRtcp(SrtpSession.create(PARAMETERS), rtcp);
        assertEquals(rtcp.length + 14, srtcp.length);
        assertArrayEquals(Arrays.copyOf(rtcp, 8), Arrays.copyOf(srtcp, 8), "first 8 bytes are not encrypted");
        assertFalse(Arrays.equals(Arrays.copyOfRange(rtcp, 8, rtcp.length),
                Arrays.copyOfRange(srtcp, 8, rtcp.length)));
    }

    @Test
    void rtcpIndexAdvancesPerPacket() {
        byte[] rtcp = rtcpReceiverReport(0x01020304, 0xCAFEBABE);
        SrtpSession sender = SrtpSession.create(PARAMETERS);
        byte[] first = encryptRtcp(sender, rtcp);
        byte[] second = encryptRtcp(sender, rtcp);
        assertFalse(Arrays.equals(first, second));
        assertFalse(Arrays.equals(Arrays.copyOfRange(first, rtcp.length, first.length),
                Arrays.copyOfRange(second, rtcp.length, second.length)), "E-flag and index differ");
    }

    @Test
    void noneCryptoSuiteIsRejected() {
        SrtpParameters none = new SrtpParameters(SrtpCryptoSuite.NONE, new byte[0], new byte[0]);
        assertThrows(IllegalArgumentException.class, () -> SrtpSession.create(none));
    }

    private static byte[] rtpPacket(int seq, int ssrc, int i) {
        byte[] payload = payload(i);
        byte[] packet = new byte[12 + payload.length];
        packet[0] = (byte) 0x80;
        packet[1] = (byte) 96;
        packet[2] = (byte) (seq >>> 8);
        packet[3] = (byte) seq;
        packet[4] = (byte) (i >>> 24);
        packet[5] = (byte) (i >>> 16);
        packet[6] = (byte) (i >>> 8);
        packet[7] = (byte) i;
        packet[8] = (byte) (ssrc >>> 24);
        packet[9] = (byte) (ssrc >>> 16);
        packet[10] = (byte) (ssrc >>> 8);
        packet[11] = (byte) ssrc;
        System.arraycopy(payload, 0, packet, 12, payload.length);
        return packet;
    }

    private static byte[] payload(int i) {
        byte[] payload = new byte[80];
        for (int j = 0; j < payload.length; j++) {
            payload[j] = (byte) (i + j * 31);
        }
        return payload;
    }

    private static byte[] hex(String s) {
        return HexFormat.of().parseHex(s);
    }

    private record LibsrtpVector(int seq, int index, String srtp) {
    }

    private static byte[] encrypt(SrtpSession session, byte[] rtp) {
        byte[] srtp = new byte[rtp.length + 10];
        int length = session.encrypt(rtp, rtp.length, srtp);
        return Arrays.copyOf(srtp, length);
    }

    private static byte[] decrypt(SrtpSession session, byte[] srtp) {
        byte[] rtp = new byte[srtp.length];
        int length = session.decrypt(srtp, srtp.length, rtp);
        return length < 0 ? null : Arrays.copyOf(rtp, length);
    }

    private static byte[] rtcpReceiverReport(int senderSsrc, int sourceSsrc) {
        byte[] packet = new byte[32];
        packet[0] = (byte) 0x81;
        packet[1] = (byte) 201;
        packet[2] = 0;
        packet[3] = (byte) (packet.length / 4 - 1);
        packet[4] = (byte) (senderSsrc >>> 24);
        packet[5] = (byte) (senderSsrc >>> 16);
        packet[6] = (byte) (senderSsrc >>> 8);
        packet[7] = (byte) senderSsrc;
        packet[8] = (byte) (sourceSsrc >>> 24);
        packet[9] = (byte) (sourceSsrc >>> 16);
        packet[10] = (byte) (sourceSsrc >>> 8);
        packet[11] = (byte) sourceSsrc;
        for (int i = 12; i < packet.length; i++) {
            packet[i] = (byte) (i * 7);
        }
        return packet;
    }

    private static byte[] encryptRtcp(SrtpSession session, byte[] rtcp) {
        byte[] srtcp = new byte[rtcp.length + 14];
        int length = session.encryptRtcp(rtcp, rtcp.length, srtcp);
        return Arrays.copyOf(srtcp, length);
    }
}
